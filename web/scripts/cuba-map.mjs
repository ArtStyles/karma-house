// Builds web/src/cuba-map.ts from geoBoundaries CUB ADM1 (OpenStreetMap, ODbL 1.0):
// https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/CUB/ADM1/geoBoundaries-CUB-ADM1_simplified.geojson
// Usage: node web/scripts/cuba-map.mjs <path-to-geojson>
import { readFileSync, writeFileSync } from 'node:fs';

const PROVINCES = ['Pinar del Río', 'Artemisa', 'La Habana', 'Mayabeque', 'Matanzas', 'Villa Clara', 'Cienfuegos', 'Sancti Spíritus',
  'Ciego de Ávila', 'Camagüey', 'Las Tunas', 'Holguín', 'Granma', 'Santiago de Cuba', 'Guantánamo', 'Isla de la Juventud'];
const ALIASES = { havana: 'la habana', 'isle of youth': 'isla de la juventud' };
const key = (name) => {
  const plain = name.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/�/g, '').toLowerCase().trim();
  return ALIASES[plain] ?? plain;
};

const WIDTH = 1000, LAT0 = 21.6, TOLERANCE = 0.9, MIN_AREA = 40;
const geo = JSON.parse(readFileSync(process.argv[2], 'utf8'));
let [minX, minY, maxX, maxY] = [Infinity, Infinity, -Infinity, -Infinity];
const cos = Math.cos((LAT0 * Math.PI) / 180);
const project = ([lon, lat]) => [lon * cos, -lat];
for (const f of geo.features) for (const poly of polygons(f.geometry)) for (const [x, y] of poly[0].map(project)) {
  minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
}
const scale = WIDTH / (maxX - minX);
const height = Math.ceil((maxY - minY) * scale);
const toView = (pt) => { const [x, y] = project(pt); return [(x - minX) * scale, (y - minY) * scale]; };

function polygons(g) { return g.type === 'Polygon' ? [g.coordinates] : g.coordinates; }
function area(ring) { let a = 0; for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) a += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]); return Math.abs(a / 2); }
function simplify(points, tol) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length); keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let max = 0, index = -1;
    const [ax, ay] = points[a], [bx, by] = points[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * points[i][0] - dx * points[i][1] + bx * ay - by * ax) / len; if (d > max) { max = d; index = i; } }
    if (max > tol) { keep[index] = 1; stack.push([a, index], [index, b]); }
  }
  return points.filter((_, i) => keep[i]);
}
// A closed ring starts and ends on the same point, so split it at the vertex farthest from the start.
function simplifyRing(ring, tol) {
  let far = 0, max = -1;
  ring.forEach(([x, y], i) => { const d = Math.hypot(x - ring[0][0], y - ring[0][1]); if (d > max) { max = d; far = i; } });
  return simplify(ring.slice(0, far + 1), tol).concat(simplify(ring.slice(far), tol).slice(1));
}
const path = (ring) => 'M' + ring.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z';

const byKey = new Map(geo.features.map((f) => [key(f.properties.shapeName), f]));
const provinces = PROVINCES.map((name) => {
  const feature = byKey.get(key(name));
  if (!feature) throw new Error(`Missing province in source data: ${name}`);
  const rings = polygons(feature.geometry).map((poly) => simplifyRing(poly[0].map(toView), TOLERANCE)).filter((r) => r.length > 3);
  const largest = Math.max(...rings.map(area));
  const d = rings.filter((r) => area(r) === largest || area(r) >= MIN_AREA).map(path).join('');
  return { name, d };
});
if (byKey.size !== PROVINCES.length) throw new Error(`Expected ${PROVINCES.length} provinces, source has ${byKey.size}`);

const out = `// Generated by web/scripts/cuba-map.mjs. Do not edit by hand.
// Province outlines © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright), via geoBoundaries (gbOpen CUB ADM1).
// Order follows PROVINCES (west to east, then Isla de la Juventud).
export const CUBA_VIEWBOX = '0 0 ${WIDTH} ${height}';
export const CUBA_PROVINCES: { name: string; d: string }[] = ${JSON.stringify(provinces, null, 0).replace(/},{/g, '},\n  {')};
`;
writeFileSync(new URL('../src/cuba-map.ts', import.meta.url), out);
console.log(`cuba-map.ts: ${provinces.length} provinces, ${Buffer.byteLength(out)} bytes, viewBox 0 0 ${WIDTH} ${height}`);
